// Context cursor choice (view only). node test/cursor-test.mjs
import { pickCursor, cursorCss } from '../src/cursor.js';
const fails = [];
const eq = (a, b, m) => { if (a !== b) { fails.push(m); console.log('  FAIL', m, JSON.stringify(a), '!=', JSON.stringify(b)); } else console.log('  ok ', m); };
const V = { villagers: true, military: false }, M = { villagers: false, military: true }, VM = { villagers: true, military: true }, N = { villagers: false, military: false };
const en = o => o === 1;
const R = type => ({ kind: 'resource', type, owner: -1 });
eq(pickCursor(V, R('tree'), 0, en), 'axe', 'villager + tree = axe');
eq(pickCursor(V, R('gold'), 0, en), 'pickaxe', 'villager + gold = pickaxe');
eq(pickCursor(V, R('stone'), 0, en), 'pickaxe', 'villager + stone = pickaxe');
eq(pickCursor(V, R('berries'), 0, en), 'food', 'villager + berries = food');
eq(pickCursor(V, { ...R('deer'), live: true }, 0, en), 'food', 'villager + live deer = food');
eq(pickCursor(V, { ...R('deer'), alive: false }, 0, en), 'food', 'villager + hunted deer carcass = food');
eq(pickCursor(V, { ...R('wolf'), live: true }, 0, en), 'sword', 'villager + live wolf = sword');
eq(pickCursor(V, { ...R('wolf'), live: false }, 0, en), 'food', 'villager + hunted wolf carcass = food');
eq(pickCursor(V, R('fish'), 0, en), '', 'villager + fish = normal');
eq(pickCursor(M, R('tree'), 0, en), '', 'military + tree = normal');
eq(pickCursor(V, { kind: 'building', type: 'farm', owner: 0, done: true, hp: 10, maxHp: 10 }, 0, en), 'food', 'villager + farm = food');
eq(pickCursor(V, { kind: 'building', type: 'house', owner: 0, done: false, hp: 1, maxHp: 10 }, 0, en), 'hammer', 'villager + unfinished = hammer');
eq(pickCursor(V, { kind: 'building', type: 'house', owner: 0, done: true, hp: 5, maxHp: 10 }, 0, en), 'hammer', 'villager + damaged = hammer');
eq(pickCursor(V, { kind: 'building', type: 'house', owner: 0, done: true, hp: 10, maxHp: 10 }, 0, en), '', 'villager + healthy house = normal');
eq(pickCursor(M, { kind: 'building', type: 'house', owner: 0, done: false, hp: 1, maxHp: 10 }, 0, en), '', 'military + unfinished = normal');
eq(pickCursor(M, { kind: 'unit', type: 'spear', owner: 1 }, 0, en), 'sword', 'military + enemy unit = sword');
eq(pickCursor(VM, { kind: 'building', type: 'house', owner: 1 }, 0, en), 'sword', 'mixed + enemy building = sword');
eq(pickCursor(M, { kind: 'unit', type: 'spear', owner: 2 }, 0, en), '', 'ally unit = normal');
eq(pickCursor(M, { kind: 'unit', type: 'spear', owner: 1, dead: true }, 0, en), '', 'dead = normal');
eq(pickCursor(N, { kind: 'unit', type: 'spear', owner: 1 }, 0, en), '', 'no own units = normal');
eq(pickCursor(M, null, 0, en), '', 'nothing hovered = normal');
for (const n of ['axe', 'pickaxe', 'food', 'hammer', 'sword']) eq(/^url\("data:image\/svg\+xml,.*"\) \d+ \d+, auto$/.test(cursorCss(n)), true, 'css ' + n);
eq(cursorCss(''), '', 'css normal empty');
if (fails.length) { console.log(fails.length + ' FAIL'); process.exit(1); } console.log('cursor-test OK');
